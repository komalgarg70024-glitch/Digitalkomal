export function loadAudits(): AuditReport[] {
  ensureDataDir();
  if (!fs.existsSync(AUDITS_FILE)) {
    const initial = [buildDemoAuditReport()];
    fs.writeFileSync(AUDITS_FILE, JSON.stringify(initial, null, 2), 'utf-8');
    return initial;
  }
  try {
    const raw = fs.readFileSync(AUDITS_FILE, 'utf-8');
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) return parsed;
  } catch {
    // ignore
  }
  const fallback = [buildDemoAuditReport()];
  fs.writeFileSync(AUDITS_FILE, JSON.stringify(fallback, null, 2), 'utf-8');
  return fallback;
}

export function saveAudit(report: AuditReport): void {
  ensureDataDir();
  const existing = loadAudits();
  const filtered = existing.filter((a) => a.id !== report.id);
  const updated = [report, ...filtered].slice(0, 30);
  fs.writeFileSync(AUDITS_FILE, JSON.stringify(updated, null, 2), 'utf-8');
}

export function deleteAuditById(id: string): boolean {
  ensureDataDir();
  const existing = loadAudits();
  const updated = existing.filter((a) => a.id !== id);
  fs.writeFileSync(AUDITS_FILE, JSON.stringify(updated, null, 2), 'utf-8');
  return updated.length < existing.length;
}

